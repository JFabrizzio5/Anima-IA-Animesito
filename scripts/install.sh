#!/usr/bin/env bash
# One-time setup inside WSL: Python venv, frontend packages, .env files,
# database, and a report of the local models the app will offer.
#
#   bash scripts/install.sh [--comfy-models DIR]
#
# DIR is ComfyUI's models folder as WSL sees it (/mnt/c/...). Default: what
# animesito/.env already says, else Desktop\ComfyUI\models of the Windows user.
# Safe to run again: existing .env files are kept, only what is missing is added.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="$HOME/.local/bin:$HOME/.jfast-toolchains/node/bin:$PATH"
# Compose project name: scripts/dev.sh uses the same, so both see one database.
PROJECT=animesito
DB_VOLUME="${PROJECT}_animesito_database_data"

step() { printf '\n==> %s\n' "$*"; }
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

# set_env FILE KEY VALUE: replace the KEY= line, or append it.
set_env() {
  if grep -q "^$2=" "$1"; then
    sed -i "s|^$2=.*|$2=$3|" "$1"
  else
    printf '%s=%s\n' "$2" "$3" >>"$1"
  fi
}

comfy_models=""
while [ $# -gt 0 ]; do
  case "$1" in
    --comfy-models) comfy_models="${2:?--comfy-models needs a directory}"; shift 2 ;;
    *) fail "unknown argument: $1" ;;
  esac
done

step "Checking tools"
command -v docker >/dev/null || fail "docker is not installed in this WSL distro."
docker info >/dev/null 2>&1 || fail "docker is installed but not running (sudo systemctl start docker)."
docker compose version >/dev/null 2>&1 || fail "the docker compose plugin is missing."
if ! command -v uv >/dev/null; then
  step "Installing uv into ~/.local/bin"
  curl -LsSf https://astral.sh/uv/install.sh | sh
fi
npm_bin="$(command -v npm || true)"
case "$npm_bin" in
  "" | /mnt/*)
    # On PATH through Windows interop; it cannot install Linux packages.
    fail "Node.js for Linux is missing (found: ${npm_bin:-none}). Install Node 20+ inside WSL." ;;
esac
node -e 'process.exit(Number(process.versions.node.split(".")[0]) >= 20 ? 0 : 1)' \
  || fail "Node $(node --version) is too old; the frontend needs Node 20+."
echo "docker $(docker info --format '{{.ServerVersion}}'), uv $(uv --version | cut -d' ' -f2), node $(node --version)"

step "Configuration (.env, animesito/.env)"
cd "$ROOT"
if [ ! -f .env ]; then
  if docker volume inspect "$DB_VOLUME" >/dev/null 2>&1; then
    fail "the database volume $DB_VOLUME already exists but .env does not, so its password is unknown.
Copy .env and animesito/.env from the previous install into $ROOT and run this again."
  fi
  printf '# Secrets for this workspace. Generated by scripts/install.sh.\n# Never commit this file.\nANIMESITO_DATABASE_PASSWORD=%s\n' \
    "$(openssl rand -hex 24)" >.env
  chmod 600 .env
  echo "created .env"
fi
password="$(sed -n 's/^ANIMESITO_DATABASE_PASSWORD=//p' .env)"
[ -n "$password" ] || fail ".env has no ANIMESITO_DATABASE_PASSWORD."

if [ -z "$comfy_models" ] && [ -f animesito/.env ]; then
  comfy_models="$(sed -n 's/^JFAST_COMFY_MODELS_DIR=//p' animesito/.env)"
fi
if [ -z "$comfy_models" ]; then
  win_profile="$(cd /mnt/c && cmd.exe /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')"
  [ -n "$win_profile" ] && comfy_models="$(wslpath -u "$win_profile")/Desktop/ComfyUI/models"
fi

if [ ! -f animesito/.env ]; then
  cp animesito/.env.example animesito/.env
  chmod 600 animesito/.env
  set_env animesito/.env JFAST_DB_DSN "postgresql+asyncpg://app:${password}@127.0.0.1:7790/app"
  set_env animesito/.env POSTGRES_PASSWORD "$password"
  set_env animesito/.env JFAST_CACHE_URL "redis://127.0.0.1:7792/0"
  echo "created animesito/.env"
fi
if [ -n "$comfy_models" ]; then
  set_env animesito/.env JFAST_COMFY_MODELS_DIR "$comfy_models"
fi
if [ ! -d "$comfy_models/checkpoints" ]; then
  echo "WARNING: no checkpoints folder in '${comfy_models}'. v-prediction and LoRA bases will be"
  echo "         guessed from file names. Re-run with --comfy-models /mnt/c/.../ComfyUI/models."
fi

step "Python environment (animesito/.venv)"
cd "$ROOT/animesito"
[ -x .venv/bin/python ] || uv venv --python 3.12 .venv
uv pip install --python .venv/bin/python -r requirements-dev.txt

step "Content policy check"
# The same rules the backend checks on import; a weakened copy fails here
# instead of at the first start.
.venv/bin/python -m pytest -q -p no:cacheprovider modules/policy \
  || fail "content policy tests failed: restore modules/policy/validations/policy_rules.py from git."

step "Database and cache (docker compose project '$PROJECT')"
cd "$ROOT"
set -a
# shellcheck disable=SC1091
. ./.env
set +a
docker compose -p "$PROJECT" up -d animesito-database animesito-cache
ready=""
for _ in $(seq 1 30); do
  if docker compose -p "$PROJECT" exec -T animesito-database pg_isready -U app >/dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 1
done
[ -n "$ready" ] || fail "PostgreSQL did not become ready on :7790."
cd "$ROOT/animesito"
.venv/bin/alembic upgrade head

step "Frontend packages (animesito-web)"
cd "$ROOT/animesito-web"
npm ci --no-audit --no-fund

step "Local models"
cd "$ROOT/animesito"
PYTHONPATH=. .venv/bin/python "$ROOT/scripts/models_report.py" "$comfy_models"

step "Done"
echo "Start it with Iniciar.bat on Windows, or here: bash scripts/dev.sh  ->  http://127.0.0.1:7799"
